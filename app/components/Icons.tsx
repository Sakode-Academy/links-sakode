export function DynamicIcon({ iconName, className = "w-5 h-5" }: { iconName: IconNameType; className?: string }) {
  switch (iconName) {
    case 'whatsapp':
      return <WhatsappIcon className={className} />;
    case 'instagram':
      return <InstagramIcon className={className} />;
    case 'tiktok':
      return <TiktokIcon className={className} />;
    case 'website':
      return <WebsiteIcon className={className} />;
    case 'email':
      return <EmailIcon className={className} />;
    case 'youtube':
      return <YoutubeIconSvg className={className} />;
    case 'github':
      return <GithubIconSvg className={className} />;
    case 'linkedin':
      return <LinkedinIconSvg className={className} />;
    case 'telegram':
      return <Send className={className} />;
    case 'discord':
      return <MessageSquare className={className} />;
    default:
      return <LinkIconLucide className={className} />;
  }
}

